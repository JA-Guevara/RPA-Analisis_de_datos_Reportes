def map_export_columns(df: pd.DataFrame, mapping: dict[str, str]) -> pd.DataFrame:
    # Renombra y reordena columnas para exportacion sin tocar nombres internos de BD
    renamed = df.rename(columns=mapping)
    ordered_cols = [target for target in mapping.values() if target in renamed.columns]
    remaining = [c for c in renamed.columns if c not in ordered_cols]
    return renamed[ordered_cols + remaining]
